static const UnicodeRange unicode_whitespace[] = {
    {0x000020, 0x000020},
    {0x0000A0, 0x0000A0},
    {0x001680, 0x001680},
    {0x002000, 0x00200A},
    {0x00202F, 0x00202F},
    {0x00205F, 0x00205F},
    {0x003000, 0x003000},
};

static inline bool unicode_in_ranges(
    int32_t c, const UnicodeRange *ranges, size_t count)
{
	size_t lo = 0;
	size_t hi = count;

	while (lo < hi) {
		size_t mid = lo + (hi - lo) / 2;

		if (c < ranges[mid].first)
			hi = mid;
		else if (c > ranges[mid].last)
			lo = mid + 1;
		else
			return true;
	}

	return false;
}

static inline bool is_punc(UnicodeChar c)
{
	return unicode_in_ranges(c, unicode_punctuation,
	    sizeof(unicode_punctuation) / sizeof(*unicode_punctuation));
}

static inline bool is_ws_horiz(UnicodeChar c)
{
	if (c == 0x0009)
		return true;

	return unicode_in_ranges(c, unicode_whitespace,
	    sizeof(unicode_whitespace) / sizeof(*unicode_whitespace));
}

static inline bool is_ws_vert(UnicodeChar c)
{
	switch (c) {
	case 0x000A: // LF \n
	case 0x000B: // VT \v
	case 0x000C: // FF \f
	case 0x000D: // CR \r
	case 0x0085: // NEL
	case 0x2028: // LS
	case 0x2029: // PS
		return true;
	default:
		return false;
	}
}

static inline bool is_degree_symbol(UnicodeChar c)
{
	switch (c) {
	case 0x00B0: // °
	case 0x00BA: // º
	case 0x02DA: // ˚
		return true;
	default:
		return false;
	}
}

